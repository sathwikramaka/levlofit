"""Build the `foods` seed migration from IFCT 2017 (NIN, via @ifct2017/compositions 2.0.9, MIT).

Run: python data/build_foods.py
Writes supabase/migrations/20260929170000_foods_ifct2017.sql. Values are per 100 g edible portion.
Tags drive the plan engine's excludedFoodTags (diet + allergy filters); keep them in sync with
DIET_EXCLUDES / RESTRICTION_EXCLUDES in supabase/functions/_shared/plan-engine.ts.
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data/ifct2017/package/index.csv"
OUT = ROOT / "supabase/migrations/20260929170000_foods_ifct2017.sql"

GROUP_TAGS = {
    "Animal Meat": ["meat"],
    "Poultry": ["poultry"],
    "Egg and Egg Products": ["egg"],
    "Marine Fish": ["fish"],
    "Fresh Water Fish and Shellfish": ["fish"],  # mixed group: shellfish rows also caught by NAME_TAGS
    "Marine Shellfish": ["shellfish"],
    "Marine Mollusks": ["shellfish"],
    "Milk and Milk Products": ["dairy"],
}
NAME_TAGS = [  # (regex on the English name, tags)
    (r"^(Beef|Calf|Mithun)\b", ["beef"]),  # cattle: never offered (product rule)
    (r"^Pork\b", ["pork"]),
    (r"^(Wheat|Barley)\b", ["wheat", "gluten"]),
    (r"^Ground nut", ["peanut"]),
    (r"^(Almond|Cashew|Walnut|Pistachio|Pine seed)", ["tree_nut"]),
    (r"^Soya bean", ["soy"]),
    (r"^Gingelly", ["sesame"]),
    (r"^Groundnut oil", ["peanut"]),  # refined oil is low-allergen; tagged on the safe side
    (r"^Soyabean oil", ["soy"]),
    (r"^Ghee", ["dairy"]),
    (r"prawn|shrimp|crab|lobster|mussel|oyster|clam", ["shellfish"]),  # fish groups only, see below
]
FISH_GROUPS = {"Marine Fish", "Fresh Water Fish and Shellfish", "Marine Shellfish", "Marine Mollusks"}
NOT_SUGGESTED = ("Toddy", "Arecanut", "Vanaspati")  # alcohol; carcinogenic; hydrogenated fat. Lookup only.


def col(header):
    return {c.split("; ")[-1]: i for i, c in enumerate(header)}


def hindi(local):
    m = re.search(r"\bH\. ([^;.]+)", local or "")
    return m.group(1).strip() if m else None


def num(v):
    try:
        return round(float(v), 2)
    except ValueError:
        return "null"


def q(s):
    return "null" if s is None else "'" + s.replace("'", "''") + "'"


rows = list(csv.reader(SRC.open(encoding="utf-8")))
k = col(rows[0])
values = []
for r in rows[1:]:
    name, group = r[k["name"]], r[k["grup"]]
    tags = list(GROUP_TAGS.get(group, []))
    for pattern, extra in NAME_TAGS:
        if "shellfish" in extra and group not in FISH_GROUPS:
            continue  # "Oyster mushroom" is a vegetable
        if re.search(pattern, name, re.I):
            tags += extra
    suggest = not name.startswith(NOT_SUGGESTED)
    kj = num(r[k["enerc"]])
    p, f, c = (x if x != "null" else 0 for x in (num(r[k["protcnt"]]), num(r[k["fatce"]]), num(r[k["choavldf"]])))
    atwater = 4 * p + 9 * f + 4 * c  # general Atwater factors, kcal per 100 g
    kcal = None if kj == "null" else kj / 4.184  # IFCT energy is in kJ
    # Missing energy (oils, ghee) or a value ~2x the food's own macros (one chicken cut): estimate.
    # Organic acids (lemon) and glycogen (shellfish) legitimately exceed 4/9/4, so only gross excess counts.
    estimated = kcal is None or kcal == 0 or (atwater >= 100 and kcal > 1.8 * atwater)
    if estimated:
        print(f"  estimated kcal: {r[k['code']]} {name}: source {kcal and round(kcal)} -> {round(atwater)}")
        kcal = atwater
    kcal = round(kcal)
    tag_sql = "array[" + ",".join(q(t) for t in sorted(set(tags))) + "]::text[]"
    values.append(
        f"({q(r[k['code']])},{q(name)},{q(hindi(r[k['lang']]))},{q(group)},{tag_sql},{kcal},"
        f"{num(r[k['protcnt']])},{num(r[k['fatce']])},{num(r[k['choavldf']])},{num(r[k['fibtg']])},{str(suggest).lower()},{str(estimated).lower()})"
    )

sql = f"""-- Indian Food Composition Tables 2017 (National Institute of Nutrition, ICMR, Hyderabad).
-- Source data: @ifct2017/compositions 2.0.9 (MIT, Subhajit Sahu). Generated by data/build_foods.py; do not edit by hand.
-- Values per 100 g edible portion. kcal converted from the published kJ (/4.184); see kcal_estimated.

create table public.foods (
  code text primary key,
  name text not null,
  name_hi text,
  food_group text not null,
  tags text[] not null default '{{}}',
  kcal smallint,
  protein_g numeric(6,2),
  fat_g numeric(6,2),
  carb_g numeric(6,2),
  fiber_g numeric(6,2),
  suggestible boolean not null default true,
  kcal_estimated boolean not null default false  -- true: Atwater estimate (4/9/4) because the source value was missing or inconsistent
);
create index foods_tags_idx on public.foods using gin (tags);

alter table public.foods enable row level security;
create policy "foods are public" on public.foods for select to anon, authenticated using (true);
revoke insert, update, delete on public.foods from anon, authenticated;

insert into public.foods (code, name, name_hi, food_group, tags, kcal, protein_g, fat_g, carb_g, fiber_g, suggestible, kcal_estimated) values
{",\n".join(values)};
"""
OUT.write_text(sql, encoding="utf-8")
print(f"{len(values)} foods -> {OUT.relative_to(ROOT)} ({len(sql)//1024} KB)")
