"""Build the micronutrient migration for `foods` from IFCT 2017 (NIN, via @ifct2017/compositions 2.0.9, MIT code).

Run: python data/build_food_micros.py
Writes supabase/migrations/20261016200000_food_micronutrients.sql. Additive: new nullable columns plus an update by
food code; no row is inserted or deleted. Package values are grams per 100 g edible portion; stored as mg (µg for
folate). A 0 in the package is stored as null ("no value"): the package uses 0 where IFCT has no analysis (folate is
0 for liver, which is folate-rich), so a 0 cannot be told apart from a missing value.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data/ifct2017/package/index.csv"
OUT = ROOT / "supabase/migrations/20261016200000_food_micronutrients.sql"

# (package column, table column, scale from grams)
COLS = [("ca", "calcium_mg", 1e3), ("fe", "iron_mg", 1e3), ("zn", "zinc_mg", 1e3), ("na", "sodium_mg", 1e3),
        ("k", "potassium_mg", 1e3), ("mg", "magnesium_mg", 1e3), ("vitc", "vitamin_c_mg", 1e3), ("folsum", "folate_ug", 1e6)]


def value(v, scale):
    try:
        x = float(v)
    except ValueError:
        return "null"
    return "null" if x <= 0 else repr(round(x * scale, 2))


def build():
    rows = list(csv.reader(SRC.open(encoding="utf-8")))
    k = {c.split("; ")[-1]: i for i, c in enumerate(rows[0])}
    vals = []
    for r in rows[1:]:
        code = r[k["code"]].replace("'", "''")
        vals.append(f"('{code}'," + ",".join(value(r[k[src]], s) for src, _, s in COLS) + ")")
    names = [c for _, c, _ in COLS]
    return "\n".join([
        "-- Generated by data/build_food_micros.py from IFCT 2017 (NIN) via @ifct2017/compositions 2.0.9. Do not edit.",
        "-- Per 100 g edible portion. null = no value in the source (a source 0 is stored as null; see the builder).",
        "alter table public.foods",
        ",\n".join(f"  add column if not exists {n} numeric(9,2) check ({n} is null or {n} >= 0)" for n in names) + ";",
        "",
        "update public.foods f set " + ", ".join(f"{n} = v.{n}" for n in names),
        "from (values",
        ",\n".join(vals),
        ") as v(code, " + ", ".join(names) + ")",
        "where f.code = v.code;",
        "",
    ])


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(OUT.name, OUT.stat().st_size)
